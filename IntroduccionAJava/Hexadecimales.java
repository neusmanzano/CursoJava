public class Hexadecimales {
    public static void main(String[] args) {

        byte num1 = 0x01;
        byte num2 = 0x0f;
        byte num3 = 0x10;
        byte num4 = 0x11;
        byte num5 = 0x20;

        System.out.println(num1);
        System.out.println(num2);
        System.out.println(num3);
        System.out.println(num4);
        System.out.println(num5);
    }
    
}