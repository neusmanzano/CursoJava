//
// Aplicación HolaMundo de ejemplo
//
class HolaMundo {
    public static void main( String args[] ) {
        System.out.println( "Hola Mundo!" );

        int n = 20;
        int m = 10;

        System.out.println("El resultado es: " + n);
        System.out.println("El resultado es: " + n);
        System.out.println("El resultado es: " + n + 5);
        System.out.println("El resultado es: " + (n + 5));
        System.out.println("El resultado es: " + (n + "5"));
        System.out.println();
        System.out.println("El resultado es: " + (n + m));
        System.out.println("El resultado es: " + n + m);
        System.out.println(n+m);
        System.out.println();
        System.out.println("El resultado es:");
        System.out.println(n+m);
        System.out.println();
        System.out.println("El resultado es:");
        System.out.println(n+m+".");
        System.out.println();
        System.out.println("El resultado es: " +n +m +".");

    }
}